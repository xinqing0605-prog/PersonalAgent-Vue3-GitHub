import { test, expect } from '@playwright/test'

// Set E2E_BASE_URL to an isolated packaged desktop server to verify the shipped EXE.
// Keep one account per desktop window; the desktop intentionally locks account ownership.
test('packaged desktop feedback works for a newly registered account', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.locator('#authScreen')).toBeVisible()
  const authStatus = await (await page.request.get('/api/auth/status')).json()
  await page.locator('[data-auth-method="phone"]').click()
  if (authStatus.sms_demo) await expect(page.locator('#phoneModeHint')).toContainText('不会发送短信')
  await page.locator('#phoneNumber').fill('15412345678')
  await page.locator('#sendSmsButton').click()
  await expect(page.locator('#phoneMessage')).toHaveText('请输入正确的手机号')
  await page.locator('#phoneNumber').fill('+86 17812345678')
  if (authStatus.sms_demo) {
    await page.locator('#sendSmsButton').click()
    await expect(page.locator('#phoneMessage')).toContainText('验证码：')
  }
  await page.locator('[data-auth-method="password"]').click()
  await expect(page.locator('#authScreen')).toBeVisible()
  if (!(await page.locator('#authConfirmLabel').isVisible())) await page.locator('#authSwitch').click()
  await page.locator('#authUsername').fill('Packaged' + Date.now().toString(36))
  await page.locator('#authPassword').fill('Safe1234!')
  await page.locator('#authConfirmPassword').fill('Safe1234!')
  await page.locator('#authSubmit').click()
  await expect(page.locator('#authScreen')).toBeHidden()
  for (const selector of ['#openTasks', '#openConversationPreferences', '#executionMode']) await expect(page.locator(selector)).toBeHidden()

  expect((await page.request.put('/api/model-services/qwen', { data: { name: 'Qwen', model: 'qwen3.8-max' } })).ok()).toBeTruthy()
  await page.reload()
  await page.locator('#modelStatus').click()
  await expect(page.locator('[data-chat-model="qwen"] .chat-model-provider')).toHaveText('Qwen · qwen3.8-max')
  await page.locator('#manageChatModels').click()
  const choose = async (name: string) => page.locator('#modelServiceDirectory .model-service-item').filter({ hasText: name }).click()

  await choose('OpenAI')
  await page.locator('[data-provider-edit]').click()
  await expect(page.locator('#modelServiceEditProviderType')).toHaveCount(0)
  await page.locator('#modelServiceEditName').fill('Qwen')
  await page.locator('#submitModelServiceEdit').click()
  await expect(page.locator('#modelServiceEditError')).toContainText('已存在')
  await page.screenshot({ path: test.info().outputPath('provider-duplicate.png') })
  await page.locator('#cancelModelServiceEdit').click()
  await expect(page.locator('#modelServiceHeading')).toHaveText('OpenAI')

  await page.locator('#addModelService').click()
  await expect(page.locator('#modelServiceProviderType')).toHaveCount(0)
  expect(await page.locator('#modelServiceName').evaluate((el: HTMLInputElement) => el.checkValidity())).toBe(false)
  await page.locator('#modelServiceName').fill('Qwen')
  await page.locator('#submitModelServiceCreate').click()
  await expect(page.locator('#modelServiceCreateError')).toContainText('已存在')
  await page.locator('#cancelModelServiceCreate').click()

  await choose('Qwen')
  await page.locator('[data-provider-add-model]').click()
  await page.locator('#modelServiceModel').fill('qwen3.8-max')
  await page.locator('#submitModelServiceCreate').click()
  await expect(page.locator('#modelServiceCreateError')).toContainText('同名模型')
  await page.screenshot({ path: test.info().outputPath('model-duplicate.png') })
  await page.locator('#modelServiceModel').fill('qwen-image-3.0')
  await page.locator('#submitModelServiceCreate').click()
  await expect(page.locator('#modelServiceCreateModal')).toBeHidden()
  await expect(page.locator('.provider-model-list .service-card')).toHaveCount(2)
  await page.locator('.provider-model-list .service-card').last().locator('[data-model-edit]').click()
  await page.locator('#modelServiceEditModel').fill('qwen3.8-max')
  await page.locator('#submitModelServiceEdit').click()
  await expect(page.locator('#modelServiceEditError')).toContainText('同名模型')
  await page.locator('#cancelModelServiceEdit').click()
  await expect(page.locator('.provider-model-list .service-card')).toHaveCount(2)
  await page.locator('#closeModelSettings').click()

  await page.locator('#knowledgeButton').click()
  const createButton = page.locator('#knowledgeContent [data-open-create]')
  await expect(createButton).toBeVisible()
  const buttonBox = (await createButton.boundingBox())!
  const panelBox = (await page.locator('#knowledgeContent').boundingBox())!
  expect(buttonBox.width).toBeLessThan(260)
  expect(Math.abs(buttonBox.x + buttonBox.width / 2 - panelBox.x - panelBox.width / 2)).toBeLessThan(3)
  await page.screenshot({ path: test.info().outputPath('knowledge-empty-small-button.png') })
  await page.locator('#closeKnowledge').click()
  expect((await page.request.post('/api/knowledge-bases', { data: { name: '批量上传验收' } })).ok()).toBeTruthy()
  await page.locator('#knowledgeButton').click()
  await page.locator('#knowledgeContent [data-source-action="file"]:visible').click()
  await page.locator('#knowledgeFileInput').setInputFiles(Array.from({ length: 30 }, (_,i) => ({ name: `document-${i}.txt`, mimeType: 'text/plain', buffer: Buffer.from('Knowledge test ' + i) })))
  await expect(page.locator('.document-table tbody tr')).toHaveCount(30)
  const title = page.locator('.knowledge-title-row')
  const before = (await title.boundingBox())!.y
  await page.locator('.document-table-scroll').evaluate(el => { el.scrollTop = el.scrollHeight })
  expect(await page.locator('.document-table-scroll').evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  expect((await title.boundingBox())!.y).toBe(before)
  expect(await page.locator('#knowledgeContent').evaluate(el => el.scrollTop)).toBe(0)
  await expect(page.locator('[data-toggle-sources]')).toBeInViewport()
  await expect(page.locator('.document-table thead')).toBeInViewport()
  await page.screenshot({ path: test.info().outputPath('30-documents-scrolled.png') })
  await page.locator('#closeKnowledge').click()

  await page.locator('#accountButton').click()
  await page.locator('#accountThemeButton').click()
  await page.locator('[data-theme-choice="ocean"]').click()
  await page.locator('#saveTheme').click()
  await expect(page.locator('#themeModal')).toBeHidden()
  await page.reload()
  await expect(page.locator('body')).toHaveAttribute('data-theme', 'ocean')
  await page.screenshot({ path: test.info().outputPath('theme-saved.png') })
  expect(errors).toEqual([])
  await page.locator('#accountButton').click()
  await page.locator('#accountLogoutButton').click()
})