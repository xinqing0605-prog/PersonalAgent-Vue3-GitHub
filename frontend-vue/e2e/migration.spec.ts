import { test, expect, type Page } from '@playwright/test'

const password = 'Vtest!49aQz'
async function register(page: Page) {
  await page.goto('/')
  await expect(page.locator('#authScreen')).toBeVisible()
  if (!(await page.locator('#authConfirmLabel').isVisible())) await page.locator('#authSwitch').click()
  const username = `V${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`
  await page.locator('#authUsername').fill(username)
  await page.locator('#authPassword').fill(password)
  await page.locator('#authConfirmPassword').fill(password)
  await page.locator('#authSubmit').click()
  await expect(page.locator('#authScreen')).toBeHidden()
  await expect(page.locator('#conversationList .conversation-row')).toHaveCount(1)
  return username
}
async function themeDialog(page: Page) {
  await page.locator('#accountButton').click()
  await page.locator('#accountThemeButton').click()
  await expect(page.locator('#themeModal')).toBeVisible()
}
