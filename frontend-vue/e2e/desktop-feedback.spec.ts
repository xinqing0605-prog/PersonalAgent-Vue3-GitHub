import { test, expect, type Page } from '@playwright/test'

async function setup(page: Page) {
  await page.goto('/')
  const response = await page.request.post('/api/auth/register', {data: {username: 'feedback' + Date.now().toString(36), password: 'Safe1234!'}})
  expect(response.ok()).toBeTruthy()
  expect((await page.request.put('/api/model-services/qwen', {data:{name:'Qwen'}})).ok()).toBeTruthy()
  await page.reload()
  await expect(page.locator('#authScreen')).toBeHidden()
}
test('duplicate edits show an inline error without merging or changing models', async ({page}) => {
  await setup(page)
  for (const model of ['alpha', 'beta']) expect((await page.request.post('/api/model-services', {data: {name: 'Feedback', model, service_type:'大模型', base_url:'https://example.test/v1'}})).ok()).toBeTruthy()
  await page.reload()
  await page.locator('#modelStatus').click()
  await page.locator('#manageChatModels').click()
  await page.locator('#modelServiceDirectory .model-service-item').filter({hasText:'Feedback'}).click()
  await page.locator('[data-provider-edit]').click()
  await page.locator('#modelServiceEditName').fill(' Qwen ')
  await page.locator('#submitModelServiceEdit').click()
  await expect(page.locator('#modelServiceEditError')).toContainText('已存在')
  await expect(page.locator('#modelServiceEditModal')).toBeVisible()
  await page.locator('#cancelModelServiceEdit').click()
  await expect(page.locator('.provider-model-list .service-card')).toHaveCount(2)
  await page.locator('.provider-model-list .service-card').last().locator('[data-model-edit]').click()
  await page.locator('#modelServiceEditModel').fill(' ALPHA ')
  await page.locator('#submitModelServiceEdit').click()
  await expect(page.locator('#modelServiceEditError')).toContainText('同名模型')
  await page.locator('#modelServiceEditModel').fill('gamma')
  await page.locator('#submitModelServiceEdit').click()
  await expect(page.locator('#modelServiceEditModal')).toBeHidden()
  await expect(page.locator('.provider-model-list')).toContainText('gamma')
  await page.locator('[data-provider-edit]').click()
  await page.locator('#modelServiceEditName').fill('Feedback renamed')
  await page.locator('#submitModelServiceEdit').click()
  await expect(page.locator('#modelServiceEditModal')).toBeHidden()
  await expect(page.locator('#modelServiceHeading')).toHaveText('Feedback renamed')
  await expect(page.locator('.provider-model-list .service-card')).toHaveCount(2)
})
test('large knowledge upload keeps controls fixed and scrolls document rows', async ({page}) => {
  await setup(page)
  expect((await page.request.post('/api/knowledge-bases', {data:{name:'批量资料'}})).ok()).toBeTruthy()
  await page.locator('#knowledgeButton').click()
  await page.locator('#knowledgeContent [data-source-action="file"]:visible').click()
  await page.locator('#knowledgeFileInput').setInputFiles(Array.from({length:30}, (_,i)=>({name:'document-'+i+'.txt',mimeType:'text/plain',buffer:Buffer.from('Test knowledge document '+i)})))
  await expect(page.locator('.document-table tbody tr')).toHaveCount(30)
  const titleBefore = (await page.locator('.knowledge-title-row').boundingBox())!.y
  const table = page.locator('.document-table-scroll')
  await table.evaluate(el=>{el.scrollTop=el.scrollHeight})
  expect(await table.evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
  expect((await page.locator('.knowledge-title-row').boundingBox())!.y).toBe(titleBefore)
  expect(await page.locator('#knowledgeContent').evaluate(el=>el.scrollTop)).toBe(0)
  await expect(page.locator('[data-toggle-sources]')).toBeInViewport()
  await expect(page.locator('.document-table thead')).toBeInViewport()
})
test('import drops unknown knowledge references and plan mode cannot leak into sending', async ({page}) => {
  await setup(page)
  const backup={activeId:'import-feedback',conversations:[{id:'import-feedback',title:'导入记录',messages:[],files:[],knowledgeBaseIds:['missing-library'],executionMode:'plan'}]}
  await page.locator('#stateImportInput').setInputFiles({name:'conversation.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))})
  await expect(page.locator('#conversationList')).toContainText('导入记录')
  await expect(page.locator('#knowledgeButton')).toHaveText('▤ 知识库')
  await expect(page.locator('#executionMode')).toBeHidden()
  let sent: any
  await page.route('**/api/ask/stream', route=>{
    sent=route.request().postDataJSON()
    return route.fulfill({status:200,contentType:'text/event-stream',body:'data: {"type":"done"}\n\n'})
  })
  await page.locator('#question').fill('测试自动模式')
  await page.locator('#ask').click()
  await expect.poll(()=>sent?.execution_mode).toBe('auto')
  expect(sent.knowledge_base_ids).toEqual([])
})
